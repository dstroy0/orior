// db_lite_shim.c: orior's SQLite: a process of the tree's Python that reads one request a line and answers one a line,
// in JSON. An interrupt reaches the statement running from a thread of its own
#include "db_internal.h"

const char g_cli_db_lite_shim[] =
    "import json, queue, sqlite3, sys, threading, urllib.parse\n"
    "\n"
    "conn = None\n"
    "cursor = None\n"
    "jobs = queue.Queue()\n"
    "\n"
    "def say(value):\n"
    "    sys.stdout.write(json.dumps(value) + \"\\n\")\n"
    "    sys.stdout.flush()\n"
    "\n"
    "def read():\n"
    "    for line in sys.stdin:\n"
    "        ask = json.loads(line)\n"
    "        if \"interrupt\" in ask:\n"
    "            if conn is not None:\n"
    "                conn.interrupt()\n"
    "            continue\n"
    "        jobs.put(ask)\n"
    "    jobs.put(None)\n"
    "\n"
    "def shown(value):\n"
    "    if value is None:\n"
    "        return None\n"
    "    if isinstance(value, bytes):\n"
    "        return \"0x\" + value[:256].hex().upper() + (\"\xE2\x80\xA6 (%d bytes)\" % len(value) if len(value) > 256 "
    "else \"\")\n"
    "    return str(value)\n"
    "\n"
    "threading.Thread(target=read, daemon=True).start()\n"
    "while True:\n"
    "    ask = jobs.get()\n"
    "    if ask is None:\n"
    "        break\n"
    "    try:\n"
    "        if \"open\" in ask:\n"
    "            uri = \"file:\" + urllib.parse.quote(ask[\"open\"]) + (\"?mode=ro\" if ask.get(\"readonly\") else "
    "\"?mode=rwc\")\n"
    "            conn = sqlite3.connect(uri, uri=True, isolation_level=None, check_same_thread=False)\n"
    "            say({\"version\": sqlite3.sqlite_version, \"tx\": False})\n"
    "        elif \"start\" in ask:\n"
    "            cursor = conn.execute(ask[\"start\"])\n"
    "            if cursor.description is None:\n"
    "                count = cursor.rowcount\n"
    "                cursor = None\n"
    "                say({\"done\": \"%d row%s affected\" % (count, \"\" if count == 1 else \"s\") if count >= 0 else "
    "\"\", \"tx\": conn.in_transaction})\n"
    "            else:\n"
    "                say({\"columns\": [one[0] for one in cursor.description], \"tx\": conn.in_transaction})\n"
    "        elif \"rows\" in ask:\n"
    "            rows = cursor.fetchmany(ask[\"rows\"]) if cursor is not None else []\n"
    "            kinds = [None] * (len(rows[0]) if rows else 0)\n"
    "            for row in rows:\n"
    "                for at, value in enumerate(row):\n"
    "                    if kinds[at] is None and value is not None:\n"
    "                        kinds[at] = type(value).__name__\n"
    "            done = cursor is None or len(rows) < ask[\"rows\"]\n"
    "            if done:\n"
    "                cursor = None\n"
    "            say({\"rows\": [[shown(value) for value in row] for row in rows], \"kinds\": kinds, \"done\": done, "
    "\"tx\": conn.in_transaction})\n"
    "    except sqlite3.Error as error:\n"
    "        cursor = None\n"
    "        say({\"error\": str(error), \"code\": type(error).__name__, \"tx\": conn.in_transaction if conn is not "
    "None "
    "else False})\n";
