// profile_shim.c: the shim a profiled Python program runs under: the folder the program runs in, the program, then
// the program's words, or with "-" in place of the folder, the folder it runs in
#include "profile.h"

const char g_cli_profile_shim[] =
    "\n"
    "import json, os, runpy, sys, threading, time, traceback\n"
    "MARK = \"\\x1eorior-profile \"\n"
    "EVERY = 0.005\n"
    "SEND = 0.5\n"
    "root = os.path.normcase(os.path.abspath(os.getcwd() if sys.argv[1] == \"-\" else sys.argv[1]))\n"
    "program, words = os.path.abspath(sys.argv[2]), sys.argv[3:]\n"
    "time_stacks, memory_stacks, lock, out = {}, {}, threading.Lock(), sys.stdout\n"
    "state = {\"samples\": 0, \"on\": True}\n"
    "def place(name):\n"
    "    full = os.path.normcase(os.path.abspath(name))\n"
    "    return os.path.relpath(full, root).replace(os.sep, \"/\") if full.startswith(root + os.sep) else "
    "name.replace(os.sep, \"/\")\n"
    "labels = {}\n"
    "def label(code):\n"
    "    if code not in labels:\n"
    "        name = getattr(code, \"co_qualname\", code.co_name)\n"
    "        labels[code] = name + \"\\t\" + place(code.co_filename) + \"\\t\" + str(code.co_firstlineno)\n"
    "    return labels[code]\n"
    "target = os.path.normcase(program)\n"
    "def stack_of(frame):\n"
    "    parts = []\n"
    "    while frame is not None:\n"
    "        parts.append(frame)\n"
    "        frame = frame.f_back\n"
    "    parts.reverse()\n"
    "    for at, one in enumerate(parts):\n"
    "        if os.path.normcase(os.path.abspath(one.f_code.co_filename)) == target:\n"
    "            return \"\\n\".join(label(two.f_code) for two in parts[at:])\n"
    "    return None\n"
    "def reader():\n"
    "    if sys.platform == \"win32\":\n"
    "        import ctypes\n"
    "        from ctypes import wintypes\n"
    "        class Counters(ctypes.Structure):\n"
    "            _fields_ = [(\"cb\", wintypes.DWORD), (\"faults\", wintypes.DWORD)] + [(name, ctypes.c_size_t) for "
    "name "
    "in (\"peak_set\", \"set\", \"peak_paged\", \"paged\", \"peak_unpaged\", \"unpaged\", \"private\", "
    "\"peak_private\")]\n"
    "        counters = Counters()\n"
    "        counters.cb = ctypes.sizeof(Counters)\n"
    "        current = ctypes.windll.kernel32.GetCurrentProcess\n"
    "        current.restype = wintypes.HANDLE\n"
    "        query = ctypes.windll.psapi.GetProcessMemoryInfo\n"
    "        query.argtypes = [wintypes.HANDLE, ctypes.POINTER(Counters), wintypes.DWORD]\n"
    "        process = current()\n"
    "        def read():\n"
    "            query(process, ctypes.byref(counters), counters.cb)\n"
    "            return counters.private\n"
    "        return read\n"
    "    if os.path.exists(\"/proc/self/statm\"):\n"
    "        size = os.sysconf(\"SC_PAGE_SIZE\")\n"
    "        def read():\n"
    "            with open(\"/proc/self/statm\") as handle:\n"
    "                return int(handle.read().split()[1]) * size\n"
    "        return read\n"
    "    import resource\n"
    "    scale = 1 if sys.platform == \"darwin\" else 1024\n"
    "    return lambda: resource.getrusage(resource.RUSAGE_SELF).ru_maxrss * scale\n"
    "read_memory = reader()\n"
    "main = threading.main_thread().ident\n"
    "def sample():\n"
    "    me = threading.get_ident()\n"
    "    last, before = read_memory(), None\n"
    "    while state[\"on\"]:\n"
    "        grown_on = None\n"
    "        for ident, frame in sys._current_frames().items():\n"
    "            if ident == me:\n"
    "                continue\n"
    "            key = stack_of(frame)\n"
    "            if key:\n"
    "                if grown_on is None or ident == main:\n"
    "                    grown_on = key\n"
    "                with lock:\n"
    "                    time_stacks[key] = time_stacks.get(key, 0) + 1\n"
    "                    state[\"samples\"] += 1\n"
    "        now = read_memory()\n"
    "        if now > last and grown_on:\n"
    "            put = grown_on\n"
    "            if before and before != grown_on:\n"
    "                shared = []\n"
    "                for one, two in zip(before.split(\"\\n\"), grown_on.split(\"\\n\")):\n"
    "                    if one != two:\n"
    "                        break\n"
    "                    shared.append(one)\n"
    "                put = \"\\n\".join(shared) or grown_on\n"
    "            with lock:\n"
    "                memory_stacks[put] = memory_stacks.get(put, 0) + now - last\n"
    "        last, before = now, grown_on\n"
    "        time.sleep(EVERY)\n"
    "started = time.perf_counter()\n"
    "def send(done=False, code=None):\n"
    "    with lock:\n"
    "        said = {\"time\": dict(time_stacks), \"memory\": dict(memory_stacks), \"samples\": state[\"samples\"], "
    "\"seconds\": time.perf_counter() - started}\n"
    "    if done:\n"
    "        said[\"done\"] = True\n"
    "        said[\"code\"] = code\n"
    "    out.write(MARK + json.dumps(said) + \"\\n\")\n"
    "    out.flush()\n"
    "def sender():\n"
    "    while state[\"on\"]:\n"
    "        time.sleep(SEND)\n"
    "        if state[\"on\"]:\n"
    "            send()\n"
    "threading.Thread(target=sample, daemon=True).start()\n"
    "threading.Thread(target=sender, daemon=True).start()\n"
    "sys.argv = [program] + words\n"
    "sys.path.insert(0, os.path.dirname(program))\n"
    "code = 0\n"
    "try:\n"
    "    runpy.run_path(program, run_name=\"__main__\")\n"
    "except SystemExit as leaving:\n"
    "    code = leaving.code if isinstance(leaving.code, int) else (0 if leaving.code is None else 1)\n"
    "except BaseException:\n"
    "    traceback.print_exc()\n"
    "    code = 1\n"
    "state[\"on\"] = False\n"
    "sys.stdout.flush()\n"
    "send(True, code)\n"
    "os._exit(code)\n";
